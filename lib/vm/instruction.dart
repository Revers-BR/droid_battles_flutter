/// podem compartilhar opcode quando o C++ original tinha aliases de
/// mnemonico pro mesmo valor (ex.: "jae"/"jnb" == 0x3F); para decodificar
/// bytecode -> texto pegue a primeira ocorrencia.
InstructionDef? instructionByOpcode(int opcode) {
  for (final instr in kInstructionTable) {
    if (instr.opcode == opcode) return instr;
  }
  return null;
}
