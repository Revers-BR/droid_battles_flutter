// Porte de src/instruktion.h e src/instruktion.cpp (droidbattles original).
//
// `InstructionDef` guarda um par mnemonico/operandos e o opcode que ele
// vira quando montado — e a tabela usada tanto pelo assembler (texto ->
// bytecode) quanto pelo desassemblador/depurador (bytecode -> texto).
// `kInstructionTable` foi gerada automaticamente a partir do array
// original `Instruction::instructions[247]`, opcode por opcode, para
// não haver risco de erro de transcrição manual — os 247 registros
// batem 1:1 com o C++.

/// Tipos de operando reconhecidos pelo assembler (era o enum `Types` em
/// instruktion.h).
enum InstrType {
  none,
  label,
  mnemonic,
  value,
  memAddress,
  register,
  constDecl,
  offset,
  varDecl,
  cpuBoot,
  cpuStack,
  db,
  bitId,
  registerRef,
  interrupt,
}

/// Um registro da tabela de instrucoes: mnemonico, tipos/tamanhos dos
/// operandos e o opcode de 1 byte correspondente.
class InstructionDef {
  final String mnemonic;
  final InstrType arg1Type;
  final InstrType arg2Type;
  final int bits; // tamanho "principal" da instrucao (0, 8 ou 16)
  final int arg1Bits;
  final int arg2Bits;
  final int opcode;

  const InstructionDef(
    this.mnemonic,
    this.arg1Type,
    this.arg2Type,
    this.bits,
    this.arg1Bits,
    this.arg2Bits,
    this.opcode,
  );

  /// Fiel a `Instruction::checkmatch` do original: compara mnemonico e
  /// tipos de operando, e aceita bits==0 como "livre" (idem ao C++, que
  /// tambem trata bit==0 && bits==16 como compativel).
  bool checkMatch(String mnem, InstrType a1t, InstrType a2t, int bit) {
    return mnem == mnemonic &&
        arg1Type == a1t &&
        arg2Type == a2t &&
        ((bit == bits || bits == 0) || (bit == 0 && bits == 16));
  }
}

